/* ============================================================================
 * gen-aisc-data.js — build js/aisc-data.js from the AISC Shapes Database.
 *
 *   node tools/gen-aisc-data.js path/to/aisc-shapes-database-v15.0.json
 *
 * Input: the AISC Shapes Database exported as JSON (an array of rows with
 * AISC_Manual_Label, Type, A [in^2], W [lb/ft]) — e.g. the copy shipped in the
 * npm package "aisc" (BSD-3), which matches AISC's original v15.0 .xlsx for
 * every shape. The truss solver only needs the area A; weight is kept so
 * learners can see the steel cost of a choice.
 *
 * Double angles (2L) are listed by AISC once per gap and per LLBB/SLBB
 * orientation; their area is identical, so they are collapsed to one entry
 * per size (this script verifies the areas really do agree).
 * ==========================================================================*/
'use strict';

const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  console.error('usage: node tools/gen-aisc-data.js <aisc-shapes-database.json>');
  process.exit(2);
}
const rows = JSON.parse(fs.readFileSync(src, 'utf8').replace(/^﻿/, ''));

// Display families, in the order they appear in the app.
const FAMILIES = [
  ['W', 'W — wide flange'],
  ['HSSR', 'HSS — square & rectangular'],
  ['HSSC', 'HSS — round'],
  ['PIPE', 'Pipe'],
  ['L', 'L — single angles'],
  ['2L', '2L — double angles'],
  ['T', 'WT, MT & ST — tees'],
  ['C', 'C & MC — channels'],
  ['HP', 'HP — bearing piles'],
  ['MS', 'M & S — other I-shapes'],
];

function familyOf(row) {
  switch (row.Type) {
    case 'W': return 'W';
    case 'M': case 'S': return 'MS';
    case 'HP': return 'HP';
    case 'C': case 'MC': return 'C';
    case 'L': return 'L';
    case '2L': return '2L';
    case 'WT': case 'MT': case 'ST': return 'T';
    case 'PIPE': return 'PIPE';
    case 'HSS': // round HSS have two dimensions (OD x t), rectangular have three
      return row.AISC_Manual_Label.split('X').length === 2 ? 'HSSC' : 'HSSR';
    default: return null;
  }
}

const out = Object.fromEntries(FAMILIES.map(([id]) => [id, []]));
const twoL = new Map(); // base label -> { A, W, variants }
let skipped = 0;

for (const r of rows) {
  const label = String(r.AISC_Manual_Label).trim();
  const A = Number(r.A), W = Number(r.W);
  const fam = familyOf(r);
  if (!fam || !(A > 0) || !(W > 0)) { skipped++; continue; }
  if (fam === '2L') {
    // "2L6X4X3/4X3/4LLBB" -> base "2L6X4X3/4" (legs x legs x thickness)
    const base = label.split('X').slice(0, 3).join('X').replace(/(LLBB|SLBB)$/, '');
    const g = twoL.get(base);
    if (!g) twoL.set(base, { A, W, variants: 1 });
    else {
      if (Math.abs(g.A - A) > 1e-9 || Math.abs(g.W - W) > 1e-9) {
        throw new Error(`2L variants of ${base} disagree: A ${g.A} vs ${A}, W ${g.W} vs ${W}`);
      }
      g.variants++;
    }
    continue;
  }
  out[fam].push([label, A, W]);
}
for (const [base, g] of twoL) out['2L'].push([base, g.A, g.W]);

const total = Object.values(out).reduce((n, a) => n + a.length, 0);
const famJs = FAMILIES.map(([id, name]) =>
  `    { id: ${JSON.stringify(id)}, name: ${JSON.stringify(name)}, shapes: [\n` +
  out[id].map((s) => `      ${JSON.stringify(s)},`).join('\n') + '\n    ] },').join('\n');

const js = `/* ============================================================================
 * aisc-data.js — GENERATED by tools/gen-aisc-data.js. Do not edit by hand.
 *
 * Source: AISC Shapes Database v15.0 (${rows.length} shapes; ${total} listed here
 * after collapsing double-angle gap/orientation variants, which share one area).
 * Each shape: [AISC manual label, area A (in^2), nominal weight W (lb/ft)],
 * in AISC database order. HSS and pipe areas use AISC's design wall thickness.
 * ==========================================================================*/
(function (global) {
  'use strict';
  global.AISC_DATA = {
    source: 'AISC Shapes Database v15.0',
    families: [
${famJs}
    ],
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

const dest = path.join(__dirname, '..', 'js', 'aisc-data.js');
fs.writeFileSync(dest, js);
console.log(`Wrote ${path.relative(process.cwd(), dest)}: ${total} shapes ` +
  `(${rows.length} in source, ${skipped} skipped, ${[...twoL.values()].reduce((n, g) => n + g.variants, 0)} 2L variants -> ${twoL.size}).`);
for (const [id, name] of FAMILIES) console.log(`  ${name.padEnd(30)} ${out[id].length}`);
