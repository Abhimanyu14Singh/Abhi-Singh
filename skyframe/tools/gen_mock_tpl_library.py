"""Write js/mock_tpl_library_data.js: the ?mock=1 data of the structural-
system template library (D4) - the backend catalogue entries (GET
/api/model/templates, system templates only), the frame-section dicts of
every default AISC shape and the default material of every library
standard, exactly as the backend serialises them.

usage (from skyframe/):
    python3 tools/gen_mock_tpl_library.py \
        skyframe/api/web/js/mock_tpl_library_data.js

tests/test_templates_sys.py checks the committed file is up to date.
"""
import json
import sys


def render() -> str:
    from skyframe.core import material_db, steel_db
    from skyframe.core.templates_sys import (MATERIAL_DEFAULTS, SYSTEM_IDS,
                                             _spec, catalogue_entry)
    cat = [catalogue_entry(t) for t in SYSTEM_IDS]
    shapes = {}
    for t in SYSTEM_IDS:
        for key, v in _spec(t).items():
            if v[1] == "steel":
                s = steel_db.section_from_db("aisc", v[2], "A992")
                shapes[s.name] = s.to_dict()
    mats = {}
    for std, names in MATERIAL_DEFAULTS.items():
        for n in names:
            mats[f"{std}:{n}"] = material_db.material_from_db(std, n).to_dict()
    dump = lambda o: json.dumps(o, ensure_ascii=False, separators=(",", ":"),
                                sort_keys=False)
    return ("/* GENERATED by tools/gen_mock_tpl_library.py from "
            "skyframe/core/templates_sys.py,\n"
            "   the AISC database and the material library - the ?mock=1 "
            "data of the\n   structural-system template library. Do not "
            "edit by hand. */\n"
            f"export const TPL_SYS_CATALOGUE = {dump(cat)};\n"
            f"export const TPL_SYS_SHAPES = {dump(shapes)};\n"
            f"export const TPL_SYS_MATERIALS = {dump(mats)};\n")


if __name__ == "__main__":
    sys.path.insert(0, ".")
    with open(sys.argv[1], "w", encoding="utf-8") as fh:
        fh.write(render())
    print("written", sys.argv[1])
